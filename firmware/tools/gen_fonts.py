"""
CAIDEN OS font compiler.

Rasterises licensed TTFs into 4-bit anti-aliased glyph bitmaps stored in PROGMEM (flash),
so text costs zero RAM on the ESP8266.

    python -I tools/gen_fonts.py      (run from the firmware/ folder)

Output: src/graphics/fonts/Fonts.h / Fonts.cpp

Two font sets:
  * v1 (Ubuntu / Source Code Pro): still used by the setup, idle and system screens until
    they are redesigned.
  * CAIDEN OS 2.0 "Lumen" (Inter / Outfit variable fonts, SIL OFL 1.1): exactly the 10
    instances of design2/DESIGN_LANGUAGE.md, rasterised the same way as design2/sim/caiden_sim.py
    (Inter optical size = clamp(px, 14, 32)), so the device matches the approved renders.
Large sizes are digits-only to save flash.
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
V1 = os.path.join(FW, "fonts")
V2 = os.path.join(FW, "fonts")
OUT = os.path.join(FW, "src", "graphics", "fonts")

ASCII = "".join(chr(c) for c in range(32, 127))
EXTRA = "°·µ³–−…₹←→↑↓•"
DIGITS = "0123456789:.,-+%° "
NUMS = "0123456789°%-.:,/−+ "
UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 ·°:-./+%&'"

# name, (dir, file), px, weight (None = static font), charset
FONTS = [
    # ---- v1 (legacy screens)
    ("clock",  (V1, "Ubuntu-L.ttf"), 86, None, "0123456789- "),
    ("num64",  (V1, "Ubuntu-L.ttf"), 64, None, "0123456789:°−- "),
    ("num44",  (V1, "Ubuntu-L.ttf"), 44, None, "0123456789:°−- "),
    ("num28",  (V1, "Ubuntu-R.ttf"), 28, None, "0123456789°−- "),
    ("title",  (V1, "Ubuntu-M.ttf"), 19, None, ASCII + EXTRA),
    ("bodyM",  (V1, "Ubuntu-M.ttf"), 15, None, ASCII + EXTRA),
    ("body",   (V1, "Ubuntu-R.ttf"), 15, None, ASCII + EXTRA),
    ("small",  (V1, "Ubuntu-R.ttf"), 13, None, ASCII + EXTRA),
    ("label",  (V1, "SourceCodePro-Semibold.ttf"), 11, None, ASCII + EXTRA),
    ("mono",   (V1, "SourceCodePro-Medium.ttf"), 12, None, ASCII + EXTRA),
    # ---- CAIDEN OS 2.0 "Lumen" (DESIGN_LANGUAGE.md, 10 instances)
    ("l_clock_xl", (V2, "Outfit-Variable.ttf"), 76, 300, "0123456789-."),
    ("l_clock_l",  (V2, "Outfit-Variable.ttf"), 58, 300, "0123456789-"),
    ("l_num_l",    (V2, "Outfit-Variable.ttf"), 34, 300, NUMS),
    ("l_num_m",    (V2, "Outfit-Variable.ttf"), 22, 400, NUMS),
    ("l_num_s",    (V2, "Outfit-Variable.ttf"), 16, 500, NUMS),
    ("l_display",  (V2, "Outfit-Variable.ttf"), 18, 400, ASCII),
    ("l_title",    (V2, "Inter-Variable.ttf"), 15, 600, ASCII + EXTRA),
    ("l_body",     (V2, "Inter-Variable.ttf"), 13, 500, ASCII + EXTRA),
    ("l_label",    (V2, "Inter-Variable.ttf"), 11, 600, UPPER),
    ("l_micro",    (V2, "Inter-Variable.ttf"), 10, 700, UPPER + "abcdefghijklmnopqrstuvwxyz"),
    # ---- CAIDEN OS 3 "Atelier" (design2/render_v3.py): editorial headline / quote face
    ("l_head",     (V2, "Outfit-Variable.ttf"), 23, 400, ASCII + EXTRA),
    # ---- Kinetic Lyrics hero (scratch kinetic.py): content words of the sung line
    ("l_hero",     (V2, "Outfit-Variable.ttf"), 28, 700, ASCII),
]

def load(src, px, weight):
    path = os.path.join(*src)
    f = ImageFont.truetype(path, px)
    if weight is not None:
        if "Inter" in src[1]:
            f.set_variation_by_axes([min(32, max(14, px)), weight])   # same as the simulator
        else:
            f.set_variation_by_axes([weight])
    return f

def build(name, src, px, weight, chars):
    f = load(src, px, weight)
    asc, desc = f.getmetrics()
    chars = sorted(set(chars), key=ord)
    glyphs, bits = [], bytearray()
    for ch in chars:
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bits)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            nib = [min(15, (v + 8) // 17) for v in im.tobytes()]
            if len(nib) & 1: nib.append(0)
            for i in range(0, len(nib), 2): bits.append(nib[i] << 4 | nib[i + 1])
        glyphs.append((ord(ch), off, w, h, x0, y0, adv))
    label = f"{src[1]} {px}px" + (f" w{weight}" if weight else "")
    return dict(name=name, asc=asc, desc=desc, px=px, glyphs=glyphs, bits=bits, src=label)

def main():
    os.makedirs(OUT, exist_ok=True)
    fonts = [build(*spec) for spec in FONTS]
    h = ["// GENERATED by tools/gen_fonts.py - do not edit.", "#pragma once", '#include "../Font.h"', ""]
    c = ["// GENERATED by tools/gen_fonts.py - do not edit.",
         "// Glyphs: Ubuntu (Ubuntu Font Licence 1.0), Source Code Pro, Inter, Outfit (SIL OFL 1.1).",
         '#include "Fonts.h"', ""]
    total = 0
    for fo in fonts:
        n = fo["name"]
        h.append(f"extern const Font FONT_{n.upper()};   // {fo['src']}, {len(fo['glyphs'])} glyphs")
        c.append(f"// ---- {n}: {fo['src']}")
        c.append(f"static const uint8_t {n}_bits[] PROGMEM = {{")
        b = fo["bits"]
        for i in range(0, len(b), 24): c.append("  " + ",".join(f"0x{x:02X}" for x in b[i:i+24]) + ",")
        c.append("};")
        c.append(f"static const Glyph {n}_glyphs[] PROGMEM = {{")
        for (cp, off, w, hh, x0, y0, adv) in fo["glyphs"]:
            c.append(f"  {{{cp},{off},{w},{hh},{x0},{y0},{adv}}},")
        c.append("};")
        c.append(f"const Font FONT_{n.upper()} = {{ {n}_bits, {n}_glyphs, {len(fo['glyphs'])}, {fo['asc']}, {fo['desc']}, {fo['px']} }};")
        c.append("")
        sz = len(b) + len(fo["glyphs"]) * 12
        total += sz
        print(f"{n:11s} {fo['src']:36s} glyphs={len(fo['glyphs']):3d} flash={sz/1024:6.1f} KB")
    print(f"total font flash: {total/1024:.1f} KB")
    open(os.path.join(OUT, "Fonts.h"), "w", encoding="utf-8").write("\n".join(h) + "\n")
    open(os.path.join(OUT, "Fonts.cpp"), "w", encoding="utf-8").write("\n".join(c) + "\n")

if __name__ == "__main__":
    main()
