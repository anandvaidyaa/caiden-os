#!/usr/bin/env python3
"""Compress portal/index.html into src/networking/PortalPage.h (gzip bytes in flash).

Run after editing the portal:  python tools/gen_portal.py
The clock sends these bytes as-is with "Content-Encoding: gzip".
"""
import gzip
import os

FW = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(FW, "portal", "index.html")
OUT = os.path.join(FW, "src", "networking", "PortalPage.h")

raw = open(SRC, "rb").read()
gz = gzip.compress(raw, compresslevel=9, mtime=0)       # mtime=0: reproducible output
lines = []
for i in range(0, len(gz), 24):
    lines.append("    " + ",".join("0x%02x" % b for b in gz[i:i + 24]) + ",")
h = ("#pragma once\n"
     "// GENERATED by tools/gen_portal.py from portal/index.html. Do not edit by hand.\n"
     "// CAIDEN OS settings portal, gzip (%d bytes raw).\n"
     "#include <pgmspace.h>\n#include <stddef.h>\n\n"
     "static const uint8_t PORTAL_GZ[] PROGMEM = {\n%s\n};\n"
     "static const size_t PORTAL_GZ_LEN = sizeof(PORTAL_GZ);\n") % (len(raw), "\n".join(lines))
open(OUT, "w", encoding="utf-8", newline="\n").write(h)
print("portal: %d bytes -> %d gzip" % (len(raw), len(gz)))
